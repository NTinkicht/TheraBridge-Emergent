#!/usr/bin/env node
// Reconcile installed package names/versions against Yarn v1 locked metadata.
// No tarball is fetched or verified and no legal/redistribution approval is granted.
import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
const [reviewPath,lockPath,output]=process.argv.slice(2);
if(process.argv.length!==5||!reviewPath||!lockPath||!output||new Set([reviewPath,lockPath,output]).size!==3){
 console.error('Usage: reconcile-installed-lock.mjs installed-review.json yarn.lock output.json');process.exit(2);
}
let review,lock;
try{review=JSON.parse(readFileSync(reviewPath,'utf8'));lock=readFileSync(lockPath,'utf8');}
catch{console.error('Cannot read review evidence or Yarn lock');process.exit(1);}
if(review.schema!=='therabridge-installed-license-review-v1'||review.status!=='TECHNICAL_TRIAGE_NOT_LEGAL_CLEARANCE'||
 review.legallyApproved!==0||!Array.isArray(review.records)||review.records.length!==review.totalInstalled||
 !lock.startsWith('# THIS IS AN AUTOGENERATED FILE.')||!lock.includes('# yarn lockfile v1')){
 console.error('Invalid review evidence or unsupported Yarn lock');process.exit(1);
}
const locked=new Map();
let descriptors=[],version=null,resolved=null,integrity=null;
function flush(){
 if(!descriptors.length)return;
 if(!version)throw Error('Missing version in Yarn entry');
 for(const selector of descriptors){
  const match=selector.match(/^((?:@[^/]+\/)?[^@\s]+)@(.+)$/);
  if(!match)throw Error('Unsupported Yarn selector');
  const key=JSON.stringify([match[1],version]);
  const candidates=locked.get(key)??[];
  if(!candidates.some(c=>c.resolved===resolved&&c.integrity===integrity))candidates.push({resolved,integrity});
  locked.set(key,candidates);
 }
 descriptors=[];version=null;resolved=null;integrity=null;
}
try{
 for(const line of lock.split(/\r?\n/)){
  if(!line||line.startsWith('#'))continue;
  if(!/^\s/.test(line)){
   flush();if(!line.endsWith(':'))throw Error('Unsupported top-level Yarn lock syntax');
   const matches=[...line.slice(0,-1).matchAll(/(?:^|,\s*)"?((?:@[^/]+\/)?[^@",\s]+)@([^",]+?)"?(?=,|$)/g)];
   if(!matches.length)throw Error('Malformed Yarn selectors');
   descriptors=matches.map(m=>m[1]+'@'+m[2]);
  } else if(/^  version "/.test(line)) version=line.match(/^  version "([^"]+)"/)?.[1]??null;
  else if(/^  resolved "/.test(line))resolved=line.match(/^  resolved "([^"]+)"/)?.[1]??null;
  else if(/^  integrity /.test(line))integrity=line.slice('  integrity '.length).trim();
 }
 flush();
}catch(e){console.error('Invalid lock evidence: '+e.message);process.exit(1);}
if(!locked.size){console.error('No Yarn lock packages found');process.exit(1);}
const rows=[],paths=new Set();
for(const p of review.records){
 if(!p||typeof p.name!=='string'||!p.name||typeof p.version!=='string'||!p.version||
 typeof p.installedPath!=='string'||!p.installedPath||paths.has(p.installedPath)||
 p.legalApproval!==false||p.publishedPackageTextVerified!==false||p.actualLicenseTextReviewed!==false||
 p.saasObligationsReviewed!==false||p.enterpriseRedistributionReviewed!==false||p.decision!=='UNRESOLVED'){
  console.error('Inconsistent installed evidence or improper approval');process.exit(1);
 }
 paths.add(p.installedPath);
 const candidates=locked.get(JSON.stringify([p.name,p.version]))??[];
 const status=!candidates.length?'INSTALLED_VERSION_NOT_IN_LOCK':candidates.length>1?'AMBIGUOUS_LOCK_SOURCES':
 !candidates[0].integrity||!/^(?:sha512|sha1)-[a-zA-Z0-9+/=]+$/.test(candidates[0].integrity)?'LOCK_INTEGRITY_UNAVAILABLE':
 !candidates[0].resolved?'LOCK_RESOLVED_SOURCE_UNAVAILABLE':'LOCK_METADATA_PRESENT_NOT_TARBALL_VERIFIED';
 rows.push({name:p.name,version:p.version,installedPath:p.installedPath,sourceLicenseTriage:p.triage,
  lockStatus:status,lockCandidates:candidates.map(c=>({
   resolvedSourceKind:typeof c.resolved==='string'&&/^https:\/\/(registry\.yarnpkg\.com|registry\.npmjs\.org)\//.test(c.resolved)?'PUBLIC_NPM_REGISTRY':'OTHER_OR_MISSING_SOURCE',
   resolvedSourceSha256:c.resolved?createHash('sha256').update(c.resolved).digest('hex'):null,
   declaredIntegrity:c.integrity,tarballBytesVerified:false,authoritativeLicenseTextVerified:false
  })),legalApproval:false,decision:'UNRESOLVED'});
}
rows.sort((a,b)=>a.name.localeCompare(b.name,'en')||a.version.localeCompare(b.version,'en')||a.installedPath.localeCompare(b.installedPath,'en'));
const summary={};for(const r of rows)summary[r.lockStatus]=(summary[r.lockStatus]??0)+1;
const report={schema:'therabridge-installed-lock-provenance-v1',status:'LOCK_METADATA_ONLY_NOT_TARBALL_OR_LICENSE_VERIFICATION',
 lockSha256:createHash('sha256').update(lock).digest('hex'),
 installedReviewSha256:createHash('sha256').update(readFileSync(reviewPath)).digest('hex'),
 totalInstalled:rows.length,legallyApproved:0,summary,records:rows};
writeFileSync(output,JSON.stringify(report,null,2)+'\n',{flag:'wx'});
console.log(JSON.stringify({total:rows.length,summary,legallyApproved:0}));
