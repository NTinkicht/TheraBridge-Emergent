#!/usr/bin/env node
// Combine Syft discovery with independently parsed Yarn v1 lock resolution.
// Added components are lockfile-only records, not installed/verified licenses.
import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
const [input,lockPath,output]=process.argv.slice(2);
if(!input||!lockPath||!output||process.argv.length!==5){
 console.error('Usage: reconcile-sbom.mjs syft.cdx.json yarn.lock reconciled.cdx.json');process.exit(2);
}
let bom,lock;
try{bom=JSON.parse(readFileSync(input,'utf8'));lock=readFileSync(lockPath,'utf8');}
catch{console.error('SBOM or Yarn lockfile unreadable');process.exit(1);}
if(bom.bomFormat!=='CycloneDX'||!Array.isArray(bom.components)||!lock.startsWith('# THIS IS AN AUTOGENERATED FILE.')||!lock.includes('# yarn lockfile v1')){
 console.error('Invalid source SBOM or unsupported Yarn lockfile');process.exit(1);
}
const locked=new Set();
let names=[];
for(const line of lock.split(/\r?\n/)){
 if(line&&!/^\s/.test(line)&&line.endsWith(':')){
  names=[...line.slice(0,-1).matchAll(/(?:^|,\s*)"?((?:@[^/]+\/)?[^@"\s,]+)@[^",]+?"?(?=,|$)/g)].map(m=>m[1]);
 } else if(names.length&&/^  version "/.test(line)){
  const version=line.match(/^  version "([^"]+)"/)?.[1];
  if(!version)throw Error('Malformed Yarn version');
  for(const name of names)locked.add(JSON.stringify([name,version]));
  names=[];
 }
}
if(!locked.size){console.error('No locked packages discovered');process.exit(1);}
const found=new Set(bom.components.map(c=>JSON.stringify([c.name,c.version])));
let added=0;
for(const key of [...locked].sort()){
 if(found.has(key))continue;
 const [name,version]=JSON.parse(key);
 // This represents the lock entry, not a verified installed package.
 // A Yarn alias such as string-width-cjs may not be a separately published npm package.
 const encoded=name.startsWith('@')?('%40'+name.slice(1)):name;
 const ref='urn:therabridge:yarn-lock:'+createHash('sha256').update(key).digest('hex');
 bom.components.push({type:'library',name,version,'bom-ref':ref,
  purl:'pkg:npm/'+encoded+'@'+encodeURIComponent(version),
  properties:[
   {name:'therabridge:provenance',value:'yarn.lock-only; absent from Syft scan'},
   {name:'therabridge:installation-status',value:'NOT_VERIFIED'},
   {name:'therabridge:license-status',value:'NOT_VERIFIED'}
  ]});
 found.add(key);added++;
}
writeFileSync(output,JSON.stringify(bom,null,2)+'\n',{flag:'w'});
console.log(JSON.stringify({locked:locked.size,added,scannerComponents:bom.components.length-added,
 result:'RECONCILED; LICENSES NOT VERIFIED'}));
