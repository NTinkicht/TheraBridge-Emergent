function manifestTar(bytes){
 const hdr=Buffer.alloc(512);
 hdr.write('package/package.json',0,'utf8');hdr.write('0000644\0',100,'ascii');
 hdr.write('0000000\0',108,'ascii');hdr.write('0000000\0',116,'ascii');
 hdr.write(bytes.length.toString(8).padStart(11,'0')+'\0',124,'ascii');
 hdr[156]=48;hdr.write('ustar\0',257,'ascii');
 return gzipSync(Buffer.concat([hdr,bytes,Buffer.alloc((512-bytes.length%512)%512),Buffer.alloc(1024)]));
}
