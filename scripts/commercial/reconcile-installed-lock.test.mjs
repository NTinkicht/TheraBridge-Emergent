import {test} from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,writeFileSync,readFileSync,rmSync,existsSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
const tool=fileURLToPath(new URL('./reconcile-installed-lock.mjs',import.meta.url));
function run(t,modify=x=>x,changeLock=x=>x){
 const dir=mkdtempSync(join(tmpdir(),'tb-lock-audit-'));t.after(()=>rmSync(dir,{force:true,recursive:true}));
 const records=[['alpha','1.0.0'],['@scope/bravo','2.0.0'],['missing','9.0.0']].map(([name,version],i)=>({
  name,version,installedPath:'node_modules/p'+i,triage:'FILE_PRESENT_UNREVIEWED',legalApproval:false,
  publishedPackageTextVerified:false,actualLicenseTextReviewed:false,
  saasObligationsReviewed:false,enterpriseRedistributionReviewed:false,decision:'UNRESOLVED'}));
 const report=modify({schema:'therabridge-installed-license-review-v1',status:'TECHNICAL_TRIAGE_NOT_LEGAL_CLEARANCE',
  totalInstalled:records.length,legallyApproved:0,records});
 const lock=changeLock('# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\nalpha@^1.0.0:\n  version "1.0.0"\n  resolved "https://registry.yarnpkg.com/alpha/-/alpha-1.0.0.tgz#abc"\n  integrity sha512-abcDEF==\n\n"@scope/bravo@2.0.0":\n  version "2.0.0"\n  resolved "https://registry.npmjs.org/@scope/bravo/-/bravo-2.0.0.tgz"\n  integrity sha512-ABCdef==\n');
 const inFile=join(dir,'review.json'),lockFile=join(dir,'yarn.lock'),out=join(dir,'out.json');
 writeFileSync(inFile,JSON.stringify(report));writeFileSync(lockFile,lock);
 const result=spawnSync(process.execPath,[tool,inFile,lockFile,out],{encoding:'utf8'});
 return {result,out};
}
test('matches locked package versions, retains missing entries and no commercial approval',t=>{
 const {result,out}=run(t);assert.equal(result.status,0,result.stderr);
 const r=JSON.parse(readFileSync(out,'utf8'));assert.equal(r.totalInstalled,3);assert.equal(r.legallyApproved,0);
 assert.equal(r.summary.LOCK_METADATA_PRESENT_NOT_TARBALL_VERIFIED,2);
 assert.equal(r.summary.INSTALLED_VERSION_NOT_IN_LOCK,1);
 assert(r.records.every(x=>x.legalApproval===false&&x.decision==='UNRESOLVED'));
 assert.match(r.lockSha256,/^[a-f0-9]{64}$/);
 assert.equal(r.records.find(x=>x.name==='alpha').lockCandidates[0].resolvedSourceKind,'PUBLIC_NPM_REGISTRY');
});
test('fails closed for fabricated legal approvals, duplicates and malformed lock entries',t=>{
 for(const [mut,lock] of [
  [x=>{x.legallyApproved=1;return x},x=>x],
  [x=>{x.records[0].legalApproval=true;return x},x=>x],
  [x=>{x.records[0].decision='APPROVED';return x},x=>x],
  [x=>{x.records[1].installedPath=x.records[0].installedPath;return x},x=>x],
  [x=>x,x=>x.replace('  version "1.0.0"','  unknown "1.0.0"')],
  [x=>x,x=>x.replace('# yarn lockfile v1','not yarn v1')]
 ]){
  const {result,out}=run(t,mut,lock);assert.notEqual(result.status,0);assert.equal(existsSync(out),false);
 }
});
test('retains missing integrity and untrusted sources as unresolved evidence',t=>{
 const {result,out}=run(t,x=>x,x=>x.replace('  integrity sha512-abcDEF==','').replace('https://registry.npmjs.org/@scope/bravo','https://untrusted.invalid/@scope/bravo'));
 assert.equal(result.status,0,result.stderr);
 const r=JSON.parse(readFileSync(out,'utf8'));
 assert.equal(r.records.find(x=>x.name==='alpha').lockStatus,'LOCK_INTEGRITY_UNAVAILABLE');
 assert.equal(r.records.find(x=>x.name==='@scope/bravo').lockCandidates[0].resolvedSourceKind,'OTHER_OR_MISSING_SOURCE');
});
