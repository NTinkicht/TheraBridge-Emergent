const sha=x=>createHash('sha256').update(x).digest('hex');
function tarEntry(path,content,{type=48}={}){
 const h=Buffer.alloc(512),data=Buffer.from(content);
 h.write(path,0,'utf8');h.write('0000644\0',100,'ascii');h.write('0000000\0',108,'ascii');
 h.write('0000000\0',116,'ascii');h.write(data.length.toString(8).padStart(11,'0')+'\0',124,'ascii');
 h[156]=type;h.write('ustar\0',257,'ascii');
 return Buffer.concat([h,data,Buffer.alloc((512-data.length%512)%512)]);
}
function archive(name,version,opts={}){
 const manifest=Buffer.from(JSON.stringify({name,version}));
 const entry=tarEntry(opts.path??'package/package.json',manifest,{type:opts.type??48});
 return {bytes:gzipSync(Buffer.concat([entry,Buffer.alloc(1024)])),manifest};
}
