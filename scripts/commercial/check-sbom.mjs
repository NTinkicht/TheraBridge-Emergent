#!/usr/bin/env node
// CycloneDX source coverage check; scanner metadata is not legal clearance.
import {readFileSync} from 'node:fs';
const file=process.argv[2];
const kind=process.argv[3]||'source';
const lockfile=process.argv[4]||'yarn.lock';
if(!file||!['source','image'].includes(kind)||process.argv.length>5){
 console.error('Usage: check-sbom.mjs file.cdx.json source|image [yarn.lock]');process.exit(2);
}
let doc;
try{doc=JSON.parse(readFileSync(file,'utf8'));}
catch{console.error('SBOM missing or invalid JSON');process.exit(1);}
if(doc.bomFormat!=='CycloneDX'||!/^1\.[4-9]$/.test(String(doc.specVersion||''))||
 !Array.isArray(doc.components)||doc.components.length===0){
 console.error('CycloneDX format/components missing or unsupported');process.exit(1);
}
const valid=doc.components.filter(x=>x&&typeof x.name==='string'&&x.name&&
 typeof x.version==='string'&&x.version&&typeof x.type==='string');
if(!valid.length){console.error('SBOM has no versioned components');process.exit(1);}
const npm=valid.filter(x=>String(x.purl||'').startsWith('pkg:npm/'));
if(kind==='source'){
 let lock;
 try{lock=readFileSync(lockfile,'utf8');}
 catch{console.error('Source lockfile missing or unreadable');process.exit(1);}
 if(!lock.startsWith('# THIS IS AN AUTOGENERATED FILE.')||!lock.includes('# yarn lockfile v1')){
  console.error('Unsupported yarn.lock version: cannot prove package coverage');process.exit(1);
 }
 const locked=new Set();
 let names=[];
 for(const line of lock.split(/\r?\n/)){
  if(line&&!/^\s/.test(line)&&line.endsWith(':')){
   // Each Yarn v1 header may have several selectors for the same resolved package.
   names=[...line.slice(0,-1).matchAll(/(?:^|,\s*)"?((?:@[^/]+\/)?[^@"\s,]+)@[^",]+?"?(?=,|$)/g)].map(m=>m[1]);
  }else if(names.length&&/^  version "/.test(line)){
   const version=line.match(/^  version "([^"]+)"/)?.[1];
   if(version)for(const name of names)locked.add(name+'@'+version);
   names=[];
  }
 }
 if(!locked.size){console.error('Could not parse any Yarn lockfile entries');process.exit(1);}
 const discovered=new Set(npm.map(c=>c.name+'@'+c.version));
 const missing=[...locked].filter(x=>!discovered.has(x));
 if(missing.length){
  console.error(JSON.stringify({error:'Incomplete lockfile discovery',locked:locked.size,
   discovered:discovered.size,missingCount:missing.length,examples:missing.slice(0,12)}));process.exit(1);
 }
}
console.log(JSON.stringify({result:'PASS',kind,components:doc.components.length,
 versioned:valid.length,npmComponents:npm.length,
 limitation:'Scanner discovery only; asset rights and license compatibility unverified'}));
