import {test} from 'node:test';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {buildExceptionRegister} from './build-license-exception-register.mjs';
const sha=x=>createHash('sha256').update(x).digest('hex');
function fixture(){
 const lockText='# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n"alpha@^1.0.0":\n  version "1.0.0"\n  resolved "https://registry.npmjs.org/alpha/-/alpha-1.0.0.tgz"\n  integrity sha512-AAA=\n\n"beta@^2.0.0":\n  version "2.0.0"\n  resolved "https://registry.npmjs.org/beta/-/beta-2.0.0.tgz"\n  integrity sha512-BBB=\n';
 const noRoot={name:'alpha',version:'1.0.0',legalApproval:false,licenseObligationsReviewed:false,
 status:'TARBALL_INTEGRITY_VERIFIED_NO_TOP_LEVEL_LICENSE',tarballSha256:'a'.repeat(64),
 verifiedIntegrityAlgorithm:'sha512',publishedLicenseFiles:[],installedLicenseComparison:'PUBLISHER_HAS_NO_TOP_LEVEL_LICENSE'};
 const pax={name:'beta',version:'2.0.0',legalApproval:false,licenseObligationsReviewed:false,
 status:'UNRESOLVED_UNSUPPORTED_PAX_SEMANTICS',tarballSha256:'b'.repeat(64),
 installedLicenseComparison:'NOT_YET_CHECKED'};
 const direct={schema:'therabridge-publisher-tarball-evidence-v1',legallyApproved:0,records:[noRoot]};
 const transitive={schema:'therabridge-transitive-tarball-wave-v1',counts:{legallyApproved:0,uniqueVersionRows:1},records:[pax]};
 const installed={schema:'therabridge-installed-license-file-inventory-v1',approved:0,count:2,packages:[
 {name:'alpha',version:'1.0.0',installedPath:'node_modules/alpha',commercialApproval:false,actualLicenseTextReviewed:false,
  foundLicenseFiles:[{file:'LICENSE',sha256:'c'.repeat(64)}]},
 {name:'beta',version:'2.0.0',installedPath:'node_modules/beta',commercialApproval:false,actualLicenseTextReviewed:false,foundLicenseFiles:[]}]};
 const assets={schema:'therabridge-com02-consolidated-obligations-queue-v1',counts:{legallyApproved:0},
 assets:[{path:'assets/brand/logo.png',sha256:'d'.repeat(64),bytes:12,approval:false,
 rightsHolder:'NOT_VERIFIED',saasRights:'PENDING_LEGAL_REVIEW',enterpriseRedistributionRights:'PENDING_LEGAL_REVIEW'}]};
 return {direct,transitive,installed,lockText,assets};
}
test('each unresolved exact version retains publisher vs installed evidence and never grants commercial rights',()=>{
 const f=fixture(),r=buildExceptionRegister(f);
 assert.deepEqual(r.counts,{directExamined:1,nonDirectExamined:1,noPublisherRootLicense:1,
  otherUnresolvedPublisher:1,exceptions:2,nonPackageAssets:1,legallyApproved:0});
 assert.equal(r.exceptions[0].name,'alpha');
 assert.equal(r.exceptions[0].installedCopies[0].files[0].sha256,'c'.repeat(64));
 assert.equal(r.exceptions[0].upstreamLicenseTextSha256,null);
 assert.equal(r.exceptions[0].pinnedSourceUrl,'https://registry.npmjs.org/alpha/-/alpha-1.0.0.tgz');
 assert.equal(r.exceptions[1].decision,'UNRESOLVED');
 assert(r.exceptions.every(x=>x.commercialApproval===false));
 assert(r.nonPackage.every(x=>x.commercialApproval===false));
 assert.equal(r.finalNoticesIssued,false);
 assert.equal(r.commercialLicenseGranted,false);
 assert.equal(r.lockSha256,sha(f.lockText));
});
test('detects duplicate version rows and missing transitive evidence even if expected count is forged',()=>{
 const f=fixture();f.transitive.records.push({...f.transitive.records[0]});f.transitive.counts.uniqueVersionRows=2;
 assert.throws(()=>buildExceptionRegister(f),/DUPLICATE_PUBLISHER_VERSION/);
 const g=fixture();g.transitive.counts.uniqueVersionRows=100;
 assert.throws(()=>buildExceptionRegister(g),/TRANSITIVE_SCOPE_DRIFT/);
});
test('refuses fabricated upstream or component approval from input inventories',()=>{
 for(const mutation of [
  f=>f.direct.legallyApproved=1,
  f=>f.direct.records[0].legalApproval=true,
  f=>f.installed.packages[0].commercialApproval=true,
  f=>f.assets.assets[0].approval=true,
  f=>f.transitive.records[0].licenseObligationsReviewed=true,
 ]){
  const f=fixture();mutation(f);
  assert.throws(()=>buildExceptionRegister(f));
 }
});
test('a verified publisher file cannot be misclassified as verified if its installed file differs',()=>{
 const f=fixture();f.direct.records[0]={...f.direct.records[0],
  status:'TARBALL_INTEGRITY_VERIFIED_LICENSE_FILES_HASHED',publishedLicenseFiles:[{file:'LICENSE'}],
  installedLicenseComparison:'SHA256_MISMATCH'};
 assert.throws(()=>buildExceptionRegister(f),/INCONSISTENT_VERIFIED_EVIDENCE/);
});
test('strictly retains unrecognized root-license exceptions even when local installed LICENSE exists',()=>{
 const f=fixture();const r=buildExceptionRegister(f),p=r.exceptions[0];
 assert.equal(p.publisherEvidenceStatus,'TARBALL_INTEGRITY_VERIFIED_NO_TOP_LEVEL_LICENSE');
 assert.equal(p.publisherAttribution,'NOT_VERIFIED_UPSTREAM');
 assert.equal(p.enterpriseRedistributionRights,'PENDING_COUNSEL_REVIEW');
 assert.equal(p.installedCopies[0].files[0].file,'LICENSE');
});
