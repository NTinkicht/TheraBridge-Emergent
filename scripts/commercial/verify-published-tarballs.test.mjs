function file(path,data){
 const bytes=Buffer.from(data),h=Buffer.alloc(512);
 h.write(path);h.write('0000644\0',100);h.write('0000000\0',108);h.write('0000000\0',116);
 h.write(bytes.length.toString(8).padStart(11,'0')+'\0',124);
 h.write('00000000000\0',136);h.fill(32,148,156);h[156]=48;h.write('ustar\0',257);
 h.write(h.reduce((a,c)=>a+c,0).toString(8).padStart(6,'0')+'\0 ',148);
 return Buffer.concat([h,bytes,Buffer.alloc((512-bytes.length%512)%512)]);
}
function fixture(){
 const bytes=gzipSync(Buffer.concat([file('package/LICENSE','MIT synthetic test document'),file('package/NOTICE','Synthetic copyright'),file('package/nested/LICENSE','ignored'),Buffer.alloc(1024)]));
 const integrity='sha512-'+createHash('sha512').update(bytes).digest('base64');
 const lockText='# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n"alpha@^1.0.0":\n  version "1.0.0"\n  resolved "https://registry.npmjs.org/alpha/-/alpha-1.0.0.tgz"\n  integrity '+integrity+'\n';
 return {bytes,lockText,
  installed:{schema:'therabridge-installed-lock-provenance-v1',status:'LOCK_METADATA_ONLY_NOT_TARBALL_OR_LICENSE_VERIFICATION',legallyApproved:0,records:[{name:'alpha',version:'1.0.0',legalApproval:false,decision:'UNRESOLVED'}]},
  direct:{schema:'therabridge-direct-license-evidence-v1',status:'NOT_LEGAL_CLEARANCE',records:[{name:'alpha'}]}};
}
