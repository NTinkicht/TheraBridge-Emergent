import {test} from 'node:test';
import assert from 'node:assert/strict';
import {gzipSync} from 'node:zlib';
import {createHash} from 'node:crypto';
import {audit,parseLock,verifyIntegrity,extractLicenseHashes,validatedUrl} from './verify-published-tarballs.mjs';
function file(path,data){
 const bytes=Buffer.from(data),h=Buffer.alloc(512);
 h.write(path);h.write('0000644\0',100);h.write('0000000\0',108);h.write('0000000\0',116);
 h.write(bytes.length.toString(8).padStart(11,'0')+'\0',124);
 h.write('00000000000\0',136);h.fill(32,148,156);h[156]=48;h.write('ustar\0',257);
 h.write(h.reduce((a,c)=>a+c,0).toString(8).padStart(6,'0')+'\0 ',148);
 return Buffer.concat([h,bytes,Buffer.alloc((512-bytes.length%512)%512)]);
}
function fixture(){
 const bytes=gzipSync(Buffer.concat([file('package/LICENSE','MIT synthetic test document'),file('package/NOTICE','Synthetic copyright'),file('package/nested/LICENSE','ignored'),Buffer.alloc(1024)]));
 const integrity='sha512-'+createHash('sha512').update(bytes).digest('base64');
 const lockText='# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n"alpha@^1.0.0":\n  version "1.0.0"\n  resolved "https://registry.npmjs.org/alpha/-/alpha-1.0.0.tgz"\n  integrity '+integrity+'\n';
 return {bytes,lockText,
  installed:{schema:'therabridge-installed-lock-provenance-v1',status:'LOCK_METADATA_ONLY_NOT_TARBALL_OR_LICENSE_VERIFICATION',legallyApproved:0,records:[{name:'alpha',version:'1.0.0',legalApproval:false,decision:'UNRESOLVED'}]},
  direct:{schema:'therabridge-direct-license-evidence-v1',status:'NOT_LEGAL_CLEARANCE',records:[{name:'alpha'}]}};
}
test('verifies tarball SRI, hashes packaged license files, grants zero legal approvals',async()=>{
 const f=fixture();const report=await audit(f,{fetchBuffer:async()=>f.bytes});
 assert.equal(report.fetched,1);assert.equal(report.legallyApproved,0);
 assert.equal(report.summary.TARBALL_INTEGRITY_VERIFIED_LICENSE_FILES_HASHED,1);
 assert.deepEqual(report.records[0].publishedLicenseFiles.map(x=>x.file),['LICENSE','NOTICE']);
 assert.equal(report.records[0].legalApproval,false);
 assert.equal(report.records[0].licenseObligationsReviewed,false);
});
test('tampered bytes stay unresolved with no verified tarball hash',async()=>{
 const f=fixture();const r=await audit(f,{fetchBuffer:async()=>Buffer.from('tampered')});
 assert.equal(r.records[0].status,'UNRESOLVED_INTEGRITY_MISMATCH');
 assert.equal(r.records[0].tarballSha256,null);
});
test('allowlisted source validation rejects SSRF, credentials, altered ports and invalid archives',()=>{
 for(const bad of ['http://registry.npmjs.org/a.tgz','https://evil.invalid/a.tgz','https://registry.npmjs.org.evil.invalid/a.tgz','https://user:pass@registry.npmjs.org/a.tgz','https://registry.npmjs.org:8443/a.tgz','https://registry.npmjs.org/a.zip','https://registry.npmjs.org/a.tgz?x=1'])assert.throws(()=>validatedUrl(bad));
 assert.equal(validatedUrl('https://registry.yarnpkg.com/a.tgz#sha1').hostname,'registry.yarnpkg.com');
});
test('rejects corrupted archive, invalid SRI and unsupported Yarn lock structure',()=>{
 const f=fixture();
 assert.throws(()=>verifyIntegrity(f.bytes,'sha512-AAAA'),/INTEGRITY_MISMATCH/);
 assert.throws(()=>verifyIntegrity(f.bytes,'sha999-AAAA'),/INTEGRITY_UNSUPPORTED/);
 assert.throws(()=>parseLock('not yarn'),/YARN_V1_REQUIRED/);
 assert.throws(()=>extractLicenseHashes(Buffer.from('invalid')),/UNSAFE_OR_INVALID_GZIP/);
});
test('missing direct package is visible rather than silently passed',async()=>{
 const f=fixture();f.direct.records.push({name:'absent'});
 const report=await audit(f,{fetchBuffer:async()=>f.bytes});
 assert.equal(report.records.find(x=>x.name==='absent').status,'DIRECT_DEPENDENCY_NOT_INSTALLED');
});
test('rejects fabricated commercial approval in previous evidence',async()=>{
 const f=fixture();f.installed.records[0].legalApproval=true;
 await assert.rejects(()=>audit(f,{fetchBuffer:async()=>f.bytes}),/FALSE_APPROVAL/);
});
