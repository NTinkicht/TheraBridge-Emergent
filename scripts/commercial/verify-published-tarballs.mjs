#!/usr/bin/env node
// Bounded exact npm tarball evidence, not legal approval. Never stores license text.
import {readFileSync,writeFileSync} from 'node:fs';
import {createHash,timingSafeEqual} from 'node:crypto';
import {gunzipSync} from 'node:zlib';
import https from 'node:https';

const HOSTS=new Set(['registry.yarnpkg.com','registry.npmjs.org']);
const LICENSE=/^(?:licen[cs]e|copying|notice|copyright)(?:\.[a-z0-9_-]+)?$/i;
const MAX_GZIP=16*1024*1024,MAX_TAR=64*1024*1024,MAX_TEXT=1024*1024;
// Isolated exact-version exception: Next.js 14.2.35 archive exceeds 16MiB.
// No other package inherits these expanded limits; integrity remains mandatory.
const NEXT_EXCEPTION={name:'next',version:'14.2.35',gzipBytes:48*1024*1024,tarBytes:256*1024*1024};
const SWC_EXCEPTIONS=new Set(['@next/swc-linux-x64-gnu','@next/swc-linux-x64-musl']);
function packageLimits(name,version){
 if(name===NEXT_EXCEPTION.name&&version===NEXT_EXCEPTION.version)
  return {gzipBytes:NEXT_EXCEPTION.gzipBytes,tarBytes:NEXT_EXCEPTION.tarBytes,exception:'PINNED_NEXT_JS_14_2_35'};
 if(version==='14.2.33'&&SWC_EXCEPTIONS.has(name))
  return {gzipBytes:48*1024*1024,tarBytes:256*1024*1024,exception:'PINNED_NEXT_SWC_LINUX_14_2_33'};
 return {gzipBytes:MAX_GZIP,tarBytes:MAX_TAR,exception:null};
}
function parseLock(source){
 if(!source.startsWith('# THIS IS AN AUTOGENERATED FILE.')||!source.includes('# yarn lockfile v1'))throw Error('YARN_V1_REQUIRED');
 const map=new Map();let names=[],version=null,resolved=null,integrity=null;
 function flush(){
  if(!names.length)return;
  if(!version)throw Error('MISSING_VERSION');
  for(const name of names){const key=JSON.stringify([name,version]);const list=map.get(key)||[];
   if(!list.some(x=>x.resolved===resolved&&x.integrity===integrity))list.push({resolved,integrity});
   map.set(key,list);
  }
  names=[];version=null;resolved=null;integrity=null;
 }
 for(const line of source.split(/\r?\n/)){
  if(!line||line.startsWith('#'))continue;
  if(!/^\s/.test(line)){
   flush();if(!line.endsWith(':'))throw Error('BAD_SELECTOR');
   const matches=[...line.slice(0,-1).matchAll(/(?:^|,\s*)"?((?:@[^/]+\/)?[^@",\s]+)@([^",]+?)"?(?=,|$)/g)];
   if(!matches.length)throw Error('BAD_SELECTOR');
   names=matches.map(m=>m[1]);
  }else if(/^  version "/.test(line))version=line.match(/^  version "([^"]+)"/)?.[1]??null;
  else if(/^  resolved "/.test(line))resolved=line.match(/^  resolved "([^"]+)"/)?.[1]??null;
  else if(/^  integrity /.test(line))integrity=line.slice('  integrity '.length).trim();
 }
 flush();return map;
}
function validatedUrl(value){
 if(typeof value!=='string')throw Error('SOURCE_MISSING');
 let url;try{url=new URL(value.split('#')[0]);}catch{throw Error('SOURCE_INVALID');}
 if(url.protocol!=='https:'||!HOSTS.has(url.hostname)||url.port||url.username||url.password||url.search||!url.pathname.endsWith('.tgz'))throw Error('SOURCE_NOT_ALLOWLISTED');
 return url;
}
function verifyIntegrity(bytes,integrity){
 if(typeof integrity!=='string')throw Error('INTEGRITY_MISSING');
 const choices=integrity.split(/\s+/).filter(Boolean).map(x=>x.match(/^(sha512|sha384|sha256|sha1)-([A-Za-z0-9+/]+={0,2})$/)).filter(Boolean);
 if(!choices.length)throw Error('INTEGRITY_UNSUPPORTED');
 const choice=choices.find(x=>x[1]==='sha512')||choices.find(x=>x[1]==='sha384')||choices.find(x=>x[1]==='sha256')||choices[0];
 const expected=Buffer.from(choice[2],'base64'),actual=createHash(choice[1]).update(bytes).digest();
 if(expected.length!==actual.length||!timingSafeEqual(expected,actual))throw Error('INTEGRITY_MISMATCH');
 return choice[1];
}
function extractLicenseHashes(gzip,{tarBytes=MAX_TAR}={}){
 if(!Number.isSafeInteger(tarBytes)||tarBytes<1||tarBytes>NEXT_EXCEPTION.tarBytes)throw Error('INVALID_TAR_LIMIT');
 let tar;try{tar=gunzipSync(gzip,{maxOutputLength:tarBytes});}catch{throw Error('UNSAFE_OR_INVALID_GZIP');}
 const files=[];let offset=0;
 while(offset+512<=tar.length){
  const h=tar.subarray(offset,offset+512);if(h.every(x=>x===0))break;
  // PAX/GNU path overrides can change what a raw header filename means.
  // Reject instead of claiming license evidence for an effective different path.
  if([120,103,76,75].includes(h[156]))throw Error('UNSUPPORTED_TAR_EXTENDED_HEADER');
  const field=h.subarray(124,136).toString('utf8').replace(/\0.*$/,'').trim();
  if(!/^[0-7]+$/.test(field))throw Error('UNSUPPORTED_TAR_SIZE');
  const size=parseInt(field,8);
  if(!Number.isSafeInteger(size)||offset+512+size>tar.length)throw Error('TRUNCATED_TAR_ENTRY');
  const path=h.subarray(0,100).toString('utf8').replace(/\0.*$/,'');
  const prefix=h.subarray(345,500).toString('utf8').replace(/\0.*$/,'');
  const full=prefix?prefix+'/'+path:path;
  if((h[156]===0||h[156]===48)&&/^package\/[^/]+$/.test(full)){
   const name=full.slice(8);
   if(LICENSE.test(name)){
    if(size>MAX_TEXT)throw Error('OVERSIZED_LICENSE_FILE');
    const bytes=tar.subarray(offset+512,offset+512+size);
    files.push({file:name,bytes:size,sha256:createHash('sha256').update(bytes).digest('hex')});
   }
  }
  offset+=512+Math.ceil(size/512)*512;
 }
 if(offset+512>tar.length)throw Error('TRUNCATED_TAR_ARCHIVE');
 files.sort((a,b)=>a.file.localeCompare(b.file,'en'));return files;
}
async function fetchTarball(url,{gzipBytes=MAX_GZIP}={}){
 if(!Number.isSafeInteger(gzipBytes)||gzipBytes<1||gzipBytes>NEXT_EXCEPTION.gzipBytes)throw Error('INVALID_DOWNLOAD_LIMIT');
 return await new Promise((resolve,reject)=>{
  const req=https.get(url,{timeout:12000,headers:{'user-agent':'TheraBridge-license-evidence/1.0','accept':'application/octet-stream'}},res=>{
   if(res.statusCode!==200){res.resume();reject(Error('HTTP_'+res.statusCode));return;}
   const chunks=[];let total=0;
   res.on('data',part=>{total+=part.length;if(total>gzipBytes){req.destroy(Error('TARBALL_TOO_LARGE'));return;}chunks.push(part);});
   res.on('end',()=>resolve(Buffer.concat(chunks)));res.on('error',reject);
  });
  // Socket inactivity timeout alone does not stop slow trickle responses.
  const deadline=setTimeout(()=>req.destroy(Error('TOTAL_DEADLINE_EXCEEDED')),12000);
  req.on('close',()=>clearTimeout(deadline));
  req.on('timeout',()=>req.destroy(Error('TIMEOUT')));req.on('error',reject);
 });
}
async function audit({installed,lockText,direct,installedFiles=null,maxFetch=256},{fetchBuffer=fetchTarball}={}){
 if(installed.schema!=='therabridge-installed-lock-provenance-v1'||
  installed.status!=='LOCK_METADATA_ONLY_NOT_TARBALL_OR_LICENSE_VERIFICATION'||
  installed.legallyApproved!==0||!Array.isArray(installed.records))throw Error('BAD_INSTALLED_PROVENANCE');
 if(direct.schema!=='therabridge-direct-license-evidence-v1'||direct.status!=='NOT_LEGAL_CLEARANCE'||!Array.isArray(direct.records))throw Error('BAD_DIRECT_EVIDENCE');
 if(!Number.isInteger(maxFetch)||maxFetch<1||maxFetch>1024)throw Error('BAD_FETCH_LIMIT');
 if(installedFiles&&(installedFiles.schema!=='therabridge-installed-license-file-inventory-v1'||installedFiles.approved!==0||!Array.isArray(installedFiles.packages)||installedFiles.count!==installedFiles.packages.length))throw Error('BAD_INSTALLED_FILE_EVIDENCE');
 const lock=parseLock(lockText),names=[...new Set(direct.records.map(x=>x.name))].sort();
 const versions=new Map();
 for(const p of installed.records){
  if(p.legalApproval!==false||p.decision!=='UNRESOLVED')throw Error('FALSE_APPROVAL');
  if(!versions.has(p.name))versions.set(p.name,new Set());
  versions.get(p.name).add(p.version);
 }
 const records=[],jobs=[];let fetched=0;
 const installedByKey=new Map();
 for(const pkg of installedFiles?.packages??[]){
  if(pkg.commercialApproval!==false||pkg.actualLicenseTextReviewed!==false||!Array.isArray(pkg.foundLicenseFiles))throw Error('FALSE_INSTALLED_APPROVAL');
  const key=JSON.stringify([pkg.name,pkg.version]);
  if(!installedByKey.has(key))installedByKey.set(key,[]);
  installedByKey.get(key).push(pkg);
 }
 for(const name of names){
  const available=[...(versions.get(name)||[])].sort();
  if(!available.length){records.push({name,version:null,status:'DIRECT_DEPENDENCY_NOT_INSTALLED',legalApproval:false,licenseObligationsReviewed:false,installedLicenseComparison:'NOT_EVALUATED'});continue;}
  for(const version of available){
   const candidates=lock.get(JSON.stringify([name,version]))||[];
   const row={name,version,status:'PENDING',tarballSha256:null,verifiedIntegrityAlgorithm:null,publishedLicenseFiles:[],installedLicenseComparison:'NOT_YET_CHECKED',legalApproval:false,licenseObligationsReviewed:false};
   records.push(row);
   if(candidates.length!==1){row.status=candidates.length?'AMBIGUOUS_LOCK_SOURCES':'NO_LOCK_MATCH';continue;}
   if(fetched>=maxFetch){row.status='DEFERRED_BY_BOUNDED_SAMPLE';continue;}
   fetched++;
   jobs.push(async()=>{
    try{
     const url=validatedUrl(candidates[0].resolved),limits=packageLimits(name,version),bytes=await fetchBuffer(url,limits);
     row.archiveSizeException=limits.exception;
     if(!Buffer.isBuffer(bytes)||bytes.length>limits.gzipBytes)throw Error('INVALID_OR_OVERSIZED_TARBALL');
     row.verifiedIntegrityAlgorithm=verifyIntegrity(bytes,candidates[0].integrity);
     row.tarballSha256=createHash('sha256').update(bytes).digest('hex');
     row.publishedLicenseFiles=extractLicenseHashes(bytes,{tarBytes:limits.tarBytes});
     row.status=row.publishedLicenseFiles.length?'TARBALL_INTEGRITY_VERIFIED_LICENSE_FILES_HASHED':'TARBALL_INTEGRITY_VERIFIED_NO_TOP_LEVEL_LICENSE';
     if(installedFiles){
      const copies=installedByKey.get(JSON.stringify([name,version]))??[];
      if(!copies.length){row.installedLicenseComparison='INSTALLED_PACKAGE_NOT_IN_FILE_INVENTORY';return;}
      if(!row.publishedLicenseFiles.length){row.installedLicenseComparison='PUBLISHER_HAS_NO_TOP_LEVEL_LICENSE';return;}
      const result=[];
      for(const copy of copies){
       for(const pub of row.publishedLicenseFiles){
        const matching=copy.foundLicenseFiles.find(f=>f.file.toLowerCase()===pub.file.toLowerCase());
        result.push({installedPath:copy.installedPath,file:pub.file,status:!matching?'EXPECTED_FILE_MISSING':matching.sha256===pub.sha256?'EXACT_SHA256_MATCH':'SHA256_MISMATCH'});
       }
      }
      row.installedLicenseComparison=!result.length?'NO_MATCHING_TOP_LEVEL_LICENSE_FILENAME':result.some(x=>x.status==='SHA256_MISMATCH')?'SHA256_MISMATCH':result.some(x=>x.status==='EXPECTED_FILE_MISSING')?'EXPECTED_LICENSE_FILE_MISSING':'EXACT_SHA256_MATCH';
      row.installedLicenseMatches=result;
      if(row.installedLicenseComparison==='SHA256_MISMATCH')row.status='UNRESOLVED_INSTALLED_LICENSE_HASH_MISMATCH';
      if(row.installedLicenseComparison==='EXPECTED_LICENSE_FILE_MISSING')row.status='UNRESOLVED_INSTALLED_LICENSE_FILES_MISSING';
     }
    }catch(e){row.status='UNRESOLVED_'+String(e.message).replace(/[^A-Z0-9_]/g,'_').slice(0,70);}
   });
  }
 }
 // Controlled parallelism (at most six requests) avoids CI-long sequential fetches.
 let cursor=0;
 await Promise.all(Array.from({length:Math.min(6,jobs.length)},async()=>{
  while(cursor<jobs.length){const job=jobs[cursor++];await job();}
 }));
 records.sort((a,b)=>a.name.localeCompare(b.name,'en')||String(a.version).localeCompare(String(b.version),'en'));
 const summary={};for(const row of records)summary[row.status]=(summary[row.status]||0)+1;
 return {schema:'therabridge-publisher-tarball-evidence-v1',qualification:'BOUNDED VERIFIED TARBALL BYTES; NOT LEGAL CLEARANCE',
  lockSha256:createHash('sha256').update(lockText).digest('hex'),
  installedReviewSha256:createHash('sha256').update(JSON.stringify(installed)).digest('hex'),
  installedFilesPresent:Boolean(installedFiles),
  maxFetch,fetched,total:records.length,legallyApproved:0,summary,records};
}
if(import.meta.url===new URL('file://'+process.argv[1]).href){
 const [installedPath,lockPath,directPath,filesPath,outPath]=process.argv.slice(2);
 if(process.argv.length!==7||new Set([installedPath,lockPath,directPath,filesPath,outPath]).size!==5){console.error('Usage: verify-published-tarballs.mjs installed-provenance.json yarn.lock direct-evidence.json installed-license-files.json output.json');process.exit(2);}
 try{
  const result=await audit({installed:JSON.parse(readFileSync(installedPath,'utf8')),lockText:readFileSync(lockPath,'utf8'),direct:JSON.parse(readFileSync(directPath,'utf8')),installedFiles:JSON.parse(readFileSync(filesPath,'utf8'))});
  writeFileSync(outPath,JSON.stringify(result,null,2)+'\n',{flag:'wx'});
  console.log(JSON.stringify({total:result.total,fetched:result.fetched,summary:result.summary,legallyApproved:0}));
  if(result.summary.UNRESOLVED_INTEGRITY_MISMATCH||result.summary.UNRESOLVED_INSTALLED_LICENSE_HASH_MISMATCH){console.error('Verified integrity mismatch; blocking CI');process.exitCode=1;}
 }catch(e){console.error(String(e.message));process.exitCode=1;}
}
export {audit,parseLock,verifyIntegrity,extractLicenseHashes,validatedUrl,packageLimits};
