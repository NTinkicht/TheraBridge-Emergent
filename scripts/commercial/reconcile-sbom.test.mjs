import {test} from 'node:test';
import assert from 'node:assert/strict';
import {spawnSync} from 'node:child_process';
import {mkdtempSync,rmSync,writeFileSync,readFileSync} from 'node:fs';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {fileURLToPath} from 'node:url';
const reconcile=fileURLToPath(new URL('./reconcile-sbom.mjs',import.meta.url));
const check=fileURLToPath(new URL('./check-sbom.mjs',import.meta.url));
test('reconciles missing locked dependency and marks provenance unverified',t=>{
 const dir=mkdtempSync(join(tmpdir(),'tb-sbom-'));t.after(()=>rmSync(dir,{recursive:true,force:true}));
 const input=join(dir,'syft.json'),lock=join(dir,'yarn.lock'),output=join(dir,'complete.json');
 writeFileSync(lock,'# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\nreact@^18:\n  version "18.3.1"\n\nnext@^14:\n  version "14.2.35"\n');
 writeFileSync(input,JSON.stringify({bomFormat:'CycloneDX',specVersion:'1.6',components:[{type:'library',name:'react',version:'18.3.1',purl:'pkg:npm/react@18.3.1'}]}));
 const before=spawnSync(process.execPath,[check,input,'source',lock],{encoding:'utf8'});
 assert.equal(before.status,1);
 const r=spawnSync(process.execPath,[reconcile,input,lock,output],{encoding:'utf8'});assert.equal(r.status,0,r.stderr);
 const doc=JSON.parse(readFileSync(output,'utf8'));
 const next=doc.components.find(x=>x.name==='next');
 assert(next);assert.equal(next.properties.find(x=>x.name==='therabridge:license-status').value,'NOT_VERIFIED');
 const after=spawnSync(process.execPath,[check,output,'source',lock],{encoding:'utf8'});
 assert.equal(after.status,0,after.stderr);
});
