import {test} from 'node:test';
import assert from 'node:assert/strict';
import {spawnSync} from 'node:child_process';
import {mkdtempSync,rmSync,writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';
const checker=fileURLToPath(new URL('./check-sbom.mjs',import.meta.url));
const fixture='# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n"react@^18.0.0":\n  version "18.3.1"\n\n"next@^14.0.0":\n  version "14.2.35"\n\n"@prisma/client@^5.0.0":\n  version "5.22.0"\n';
const npm=(name,version)=>({type:'library',name,version,purl:'pkg:npm/'+name+'@'+version});
const valid={bomFormat:'CycloneDX',specVersion:'1.6',components:[
 npm('react','18.3.1'),npm('next','14.2.35'),npm('@prisma/client','5.22.0')]};
function check(x,kind='source',lock=fixture){
 const dir=mkdtempSync(join(tmpdir(),'tb-cdx-'));
 try{
  const f=join(dir,'in.json'),l=join(dir,'yarn.lock');
  writeFileSync(f,JSON.stringify(x));writeFileSync(l,lock);
  return spawnSync(process.execPath,[checker,f,kind,l],{encoding:'utf8'});
 }finally{rmSync(dir,{recursive:true,force:true});}
}
test('passes source with every locked npm name/version',()=>{
 const p=check(valid);assert.equal(p.status,0,p.stderr);assert.match(p.stdout,/Scanner discovery only/);
});
test('rejects missing locked transitive dependency even with other npm components',()=>{
 const p=check({...valid,components:valid.components.slice(0,2)});
 assert.equal(p.status,1);assert.match(p.stderr,/Incomplete lockfile discovery/);
});
test('rejects incorrectly-versioned locked dependency',()=>{
 const p=check({...valid,components:[npm('react','0.0.1'),...valid.components.slice(1)]});
 assert.equal(p.status,1);assert.match(p.stderr,/react@18.3.1/);
});
test('rejects missing npm in source but accepts OS package in image',()=>{
 const x={...valid,components:[{type:'operating-system',name:'debian',version:'12'}]};
 assert.equal(check(x).status,1);assert.equal(check(x,'image').status,0);
});
test('fails closed on wrong format, malformed versions, unsupported lockfile',()=>{
 for(const x of [{...valid,bomFormat:'SPDX'},{...valid,components:[]},
 {...valid,components:[{name:'react',type:'library'}]},{...valid,specVersion:'broken'}])
  assert.equal(check(x).status,1);
 assert.equal(check(valid,'source','invalid lockfile').status,1);
});

test('known scanner exclusions are exact and disclosed; adjacent versions fail',()=>{
 const lock=fixture+'\\n"fsevents@^2.3.3":\\n  version "2.3.3"\\n';
 const ok=check(valid,'source',lock);
 assert.equal(ok.status,0,ok.stderr);
 assert.match(ok.stderr,/KNOWN_SCANNER_GAPS_NOT_VERIFIED/);
 const bad=check(valid,'source',lock+'\\n"fsevents@^9.9.9":\\n  version "9.9.9"\\n');
 assert.equal(bad.status,1);
 assert.match(bad.stderr,/fsevents@9.9.9/);
});
