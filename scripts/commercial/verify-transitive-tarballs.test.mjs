import {test} from 'node:test';
import assert from 'node:assert/strict';
import {gzipSync} from 'node:zlib';
import {createHash} from 'node:crypto';
import {auditTransitive} from './verify-transitive-tarballs.mjs';

function tarFile(path,content){
 const body=Buffer.from(content),header=Buffer.alloc(512);
 header.write(path);header.write('0000644\0',100);header.write('0000000\0',108);header.write('0000000\0',116);
 header.write(body.length.toString(8).padStart(11,'0')+'\0',124);
 header.write('00000000000\0',136);header.fill(32,148,156);header[156]=48;header.write('ustar\0',257);
 header.write(header.reduce((sum,v)=>sum+v,0).toString(8).padStart(6,'0')+'\0 ',148);
 return Buffer.concat([header,body,Buffer.alloc((512-body.length%512)%512)]);
}
function fixture(){
 const tar=gzipSync(Buffer.concat([tarFile('package/LICENSE','MIT synthetic only'),Buffer.alloc(1024)]));
 const integrity=createHash('sha512').update(tar).digest('base64');
 const lockText='# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\ntransitive@^1.0.0:\n  version "1.0.0"\n  resolved "https://registry.npmjs.org/transitive/-/transitive-1.0.0.tgz"\n  integrity sha512-'+integrity+'\n';
 const installed={schema:'therabridge-installed-lock-provenance-v1',status:'LOCK_METADATA_ONLY_NOT_TARBALL_OR_LICENSE_VERIFICATION',legallyApproved:0,
  records:['direct','transitive'].map(name=>({name,version:'1.0.0',legalApproval:false,decision:'UNRESOLVED'}))};
 const pkg=(name,files)=>({name,version:'1.0.0',installedPath:'node_modules/'+name,commercialApproval:false,actualLicenseTextReviewed:false,foundLicenseFiles:files});
 const licenseHash=createHash('sha256').update('MIT synthetic only').digest('hex');
 const installedFiles={schema:'therabridge-installed-license-file-inventory-v1',approved:0,count:2,packages:[pkg('direct',[]),pkg('transitive',[{file:'LICENSE',sha256:licenseHash}])]};
 const direct={schema:'therabridge-direct-license-evidence-v1',status:'NOT_LEGAL_CLEARANCE',records:[{name:'direct',commercialApproval:false}]};
 return {tar,lockText,installed,installedFiles,direct,maxFetch:2};
}
test('only non-direct version tarballs are queried, LICENSE hashes match and approvals stay false',async()=>{
 const f=fixture(),urls=[];
 const report=await auditTransitive(f,{fetchBuffer:async url=>{urls.push(url.href);return f.tar;}});
 assert.equal(urls.length,1);assert.match(urls[0],/transitive/);
 assert.equal(report.counts.physicalNonDirectCopies,1);
 assert.equal(report.counts.attempted,1);
 assert.equal(report.counts.verifiedMatchingInstalledLicense,1);
 assert.equal(report.counts.legallyApproved,0);
 assert.equal(report.records[0].legalApproval,false);
 assert.equal(report.records[0].installedLicenseComparison,'EXACT_SHA256_MATCH');
});
test('transitive publisher LICENSE mismatch is unresolved',async()=>{
 const f=fixture();f.installedFiles.packages[1].foundLicenseFiles[0].sha256='0'.repeat(64);
 const r=await auditTransitive(f,{fetchBuffer:async()=>f.tar});
 assert.equal(r.records[0].status,'UNRESOLVED_INSTALLED_LICENSE_HASH_MISMATCH');
 assert.equal(r.counts.verifiedMatchingInstalledLicense,0);
});
test('scope excludes all direct names and rejects unsafe approvals',async()=>{
 const f=fixture();f.installedFiles.packages[1].commercialApproval=true;
 await assert.rejects(()=>auditTransitive(f,{fetchBuffer:async()=>f.tar}),/BAD_INSTALLED_EVIDENCE/);
 const g=fixture();g.direct.records[0].commercialApproval=true;
 await assert.rejects(()=>auditTransitive(g,{fetchBuffer:async()=>g.tar}),/BAD_DIRECT_DECLARATIONS/);
});
test('exact version without declared lock source never becomes verified',async()=>{
 const f=fixture();f.lockText=f.lockText.replace('  integrity sha512-','  integrity absent-');
 const r=await auditTransitive(f,{fetchBuffer:async()=>f.tar});
 assert.equal(r.records[0].status,'UNRESOLVED_INTEGRITY_UNSUPPORTED');
});

test('complete installed non-direct scope is classified without sample deferrals',async()=>{
 const f=fixture();delete f.maxFetch;
 const report=await auditTransitive(f,{fetchBuffer:async()=>f.tar});
 assert.equal(report.maxFetch,768);
 assert.equal(report.counts.deferred,0);
 assert.equal(report.status,'ALL_INSTALLED_NON_DIRECT_VERSIONS_CLASSIFIED_NOT_LEGAL_APPROVAL');
 assert.equal(report.counts.legallyApproved,0);
});
test('unmatched lock evidence remains unresolved even under exhaustive classification',async()=>{
 const f=fixture();delete f.maxFetch;f.lockText=f.lockText.replace('transitive@^1.0.0','unrelated@^1.0.0');
 const report=await auditTransitive(f,{fetchBuffer:async()=>f.tar});
 assert.equal(report.counts.deferred,0);
 assert.equal(report.records[0].status,'NO_LOCK_MATCH');
 assert.equal(report.counts.verifiedMatchingInstalledLicense,0);
});
